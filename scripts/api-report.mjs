// Prints the public API, as the built type declarations describe it, to
// api/recovery-probe.api.md. With --check, fails when that file is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const reportFile = fileURLToPath(
  new URL('../api/recovery-probe.api.md', import.meta.url),
)
const pkg = JSON.parse(
  readFileSync(new URL('../package.json', import.meta.url), 'utf8'),
)
const entries = Object.entries(pkg.exports)
  .map(([subpath, target]) => ({
    name: subpath === '.' ? pkg.name : `${pkg.name}/${subpath.slice(2)}`,
    file: fileURLToPath(new URL(`../${target.types}`, import.meta.url)),
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))

const program = ts.createProgram(
  entries.map((entry) => entry.file),
  {
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    noEmit: true,
  },
)
const checker = program.getTypeChecker()
const printer = ts.createPrinter({ removeComments: true })

// Type parameters and members also declare names, but they print with their parent.
const DECLARATIONS = new Set([
  ts.SyntaxKind.ClassDeclaration,
  ts.SyntaxKind.EnumDeclaration,
  ts.SyntaxKind.FunctionDeclaration,
  ts.SyntaxKind.InterfaceDeclaration,
  ts.SyntaxKind.ModuleDeclaration,
  ts.SyntaxKind.TypeAliasDeclaration,
  ts.SyntaxKind.VariableDeclaration,
])

const isPackageDeclaration = (node) =>
  DECLARATIONS.has(node.kind) &&
  node.getSourceFile().fileName.replaceAll('\\', '/').includes('/dist/')

function resolve(symbol) {
  return symbol.flags & ts.SymbolFlags.Alias
    ? checker.getAliasedSymbol(symbol)
    : symbol
}

function print(node) {
  const text = printer.printNode(
    ts.EmitHint.Unspecified,
    node,
    node.getSourceFile(),
  )
  return ts.isVariableDeclaration(node) ? `const ${text};` : text
}

/** The name a type node refers to, if any: `Name`, `import('…').Name` or `typeof name`. */
function referencedName(node) {
  if (ts.isTypeReferenceNode(node)) return node.typeName
  if (ts.isExpressionWithTypeArguments(node)) return node.expression
  if (ts.isImportTypeNode(node)) return node.qualifier
  if (ts.isTypeQueryNode(node)) return node.exprName
}

/** The package's own declarations of what `node` refers to. */
function referencedDeclarations(node) {
  const found = []
  const visit = (child) => {
    const name = referencedName(child)
    const symbol = name && checker.getSymbolAtLocation(name)
    if (symbol) found.push(...(resolve(symbol).declarations ?? []))
    ts.forEachChild(child, visit)
  }
  visit(node)
  return found.filter(isPackageDeclaration)
}

const referenced = new Set()
function collectReferences(declarations) {
  const queue = [...declarations]
  while (queue.length) {
    for (const declaration of referencedDeclarations(queue.shift())) {
      const text = print(declaration)
      if (referenced.has(text)) continue
      referenced.add(text)
      queue.push(declaration)
    }
  }
}

const exported = new Set()
const sections = entries.map(({ name, file }) => {
  const source = program.getSourceFile(file)
  if (!source) throw Error(`${file} is missing; run npm run build first`)
  const module = checker.getSymbolAtLocation(source)
  const exports = checker
    .getExportsOfModule(module)
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
  const blocks = exports.flatMap((symbol) => {
    const declarations = resolve(symbol).declarations ?? []
    collectReferences(declarations)
    return declarations.map((declaration) => {
      const text = print(declaration)
      exported.add(text)
      return `// ${symbol.name}\n${text}`
    })
  })
  return `## ${name}\n\n\`\`\`ts\n${blocks.join('\n\n')}\n\`\`\``
})
const shared = [...referenced]
  .filter((text) => !exported.has(text))
  .sort((a, b) => a.localeCompare(b, 'en'))

const report = `# Public API

Generated by \`npm run api:report\` from the type declarations in \`dist\`. CI fails when it is out of date, so a change to the public API shows up here in review.

${sections.join('\n\n')}

## Types the exports refer to

\`\`\`ts
${shared.join('\n\n')}
\`\`\`
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(reportFile, 'utf8')
  } catch {}
  if (current !== report) {
    console.error(
      'api/recovery-probe.api.md is out of date. Run `npm run api:report` and review the change.',
    )
    process.exitCode = 1
  }
} else {
  writeFileSync(reportFile, report)
}
